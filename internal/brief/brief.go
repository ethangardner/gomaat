// Package brief renders a one-page Markdown overview of a log by running
// several analyses in-process, as a starting ARCHITECTURE.md or context for
// someone (or an agent) new to the codebase.
package brief

import (
	"cmp"
	"fmt"
	"path"
	"slices"
	"strings"
	"time"

	"github.com/ethangardner/gomaat/internal/analysis"
	"github.com/ethangardner/gomaat/internal/markdown"
	"github.com/ethangardner/gomaat/internal/model"
)

type Options struct {
	Top           int       // max rows per table or list; 0 = no limit
	Now           time.Time // reference date for activity ages
	DormantMonths int       // age in months at which an entity counts as dormant
	Grouped       bool      // entities are already -g groups, so don't roll them up by directory
}

// couplingOpts loosens the coupling command's defaults (5 revisions, 5
// shared) so a small or young repository still shows its strongest pairs.
var couplingOpts = model.Options{MinRevs: 2, MinSharedRevs: 2, MinCoupling: 30, MaxCoupling: 100, MaxChangesetSize: 30}

// Render returns the brief for commits as Markdown: a summary, hotspots,
// coupling, main developers per component, active vs. dormant entities, and
// a suggested reading order.
func Render(commits []model.Commit, opts Options) string {
	var b strings.Builder
	b.WriteString("# Architecture brief\n\nGenerated by gomaat from version-control history. " +
		"Each section names the gomaat command to run for the full results.\n")

	section(&b, "Summary", "The dataset this brief covers (`summary`).", summary(commits))
	section(&b, "Hotspots",
		"Files changed most often (`revisions`). Frequent change is where effort and defects tend to concentrate.",
		table(commits, model.Options{}, analysis.Revisions, analysis.FormatRevisions, opts.Top))
	section(&b, "Coupling",
		"File pairs that change together in at least 30% of their commits (`coupling -n 2 -m 2`). A change to one usually means a change to the other.",
		table(commits, couplingOpts, analysis.Coupling, analysis.FormatCoupling, opts.Top))
	section(&b, "Main developers",
		"Who added the most lines to each component (`main-dev`), largest components first. Without `-g`, a component is a file's directory.",
		mainDevelopers(commits, opts))
	section(&b, "Activity", "When each file last changed (`age`).", activity(commits, opts))
	section(&b, "Suggested reading order",
		"Files that change together with the most other files (`soc`): the center of the system's change patterns. Start here.",
		readingOrder(commits, opts.Top))
	return b.String()
}

func section(b *strings.Builder, title, intro, body string) {
	fmt.Fprintf(b, "\n## %s\n\n%s\n\n%s", title, intro, body)
}

// table runs an analysis and renders its formatted rows as a Markdown table.
func table[T any](commits []model.Commit, opts model.Options, fn func([]model.Commit, model.Options) T, format func(T, model.Options) [][]string, top int) string {
	return markdown.Table(format(fn(commits, opts), opts), top)
}

func summary(commits []model.Commit) string {
	s := analysis.Summary(commits, model.Options{})
	return fmt.Sprintf("- Commits: %d\n- Entities: %d\n- Authors: %d\n- Date range: %s\n",
		s.Commits, s.Entities, s.Authors, dateRange(commits))
}

func dateRange(commits []model.Commit) string {
	if len(commits) == 0 {
		return "none"
	}
	byDate := func(a, b model.Commit) int { return cmp.Compare(a.Date, b.Date) }
	return slices.MinFunc(commits, byDate).Date + " to " + slices.MaxFunc(commits, byDate).Date
}

func mainDevelopers(commits []model.Commit, opts Options) string {
	if !opts.Grouped {
		commits = byDirectory(commits)
	}
	results := analysis.MainDev(commits, model.Options{})
	// MainDev sorts by name; stable sort keeps that as the tie-break.
	slices.SortStableFunc(results, func(a, b analysis.ContributorResult) int { return cmp.Compare(b.Total, a.Total) })
	rows := analysis.FormatMainDev(results, model.Options{})
	rows[0][0] = "component"
	return markdown.Table(rows, opts.Top)
}

// byDirectory returns a copy of commits with each entity replaced by its
// directory ("." for files at the root).
func byDirectory(commits []model.Commit) []model.Commit {
	out := make([]model.Commit, len(commits))
	for i, c := range commits {
		c.Entity = path.Dir(c.Entity)
		out[i] = c
	}
	return out
}

func activity(commits []model.Commit, opts Options) string {
	// Age sorts youngest first, so everything from the first dormant entity on
	// is dormant.
	ages := analysis.Age(commits, model.Options{AgeTimeNow: opts.Now})
	split, _ := slices.BinarySearchFunc(ages, opts.DormantMonths, func(r analysis.AgeResult, months int) int {
		return cmp.Compare(r.AgeMonths, months)
	})
	active, dormant := ages[:split], slices.Clone(ages[split:])
	slices.SortStableFunc(dormant, func(a, b analysis.AgeResult) int { return cmp.Compare(b.AgeMonths, a.AgeMonths) })

	return fmt.Sprintf("%d entities changed in the last %d months; %d untouched for %d months or more.\n\n"+
		"### Recently active\n\n%s\n### Dormant\n\nOldest first.\n\n%s",
		len(active), opts.DormantMonths, len(dormant), opts.DormantMonths,
		markdown.Table(analysis.FormatAge(active, model.Options{}), opts.Top),
		markdown.Table(analysis.FormatAge(dormant, model.Options{}), opts.Top))
}

func readingOrder(commits []model.Commit, top int) string {
	var entities []string
	for _, r := range analysis.SumOfCoupling(commits, couplingOpts) {
		// Sorted by soc descending, so the rest never changed with another file.
		if r.Soc == 0 {
			break
		}
		entities = append(entities, r.Entity)
	}
	return markdown.List(entities, top)
}
